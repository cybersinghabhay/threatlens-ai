
import html
import json
from pathlib import Path


def export_html_report(
    report: dict,
    output_path: str = "security_report.html",
) -> str:
    """Export a structured report to a standalone HTML file."""

    report_json = json.dumps(report, indent=4, ensure_ascii=False)
    safe_report_json = html.escape(report_json)

    html_content = f"""<!DOCTYPE html>
<html lang="en">
<head>
    <meta charset="UTF-8">
    <meta name="viewport" content="width=device-width, initial-scale=1.0">
    <title>ThreatLens AI - Security Report</title>
    <style>
        body {{
            font-family: Arial, sans-serif;
            max-width: 1000px;
            margin: 40px auto;
            padding: 20px;
            color: #222;
            background: #f4f6f8;
        }}
        h1 {{
            color: #17365d;
        }}
        pre {{
            background: #fff;
            border: 1px solid #ddd;
            border-radius: 8px;
            padding: 20px;
            overflow-x: auto;
            white-space: pre-wrap;
            overflow-wrap: anywhere;
        }}
        .footer {{
            color: #555;
            font-size: 0.9em;
        }}
    </style>
</head>
<body>
    <h1>ThreatLens AI Security Report</h1>
    <p>Structured investigation report generated by ThreatLens AI.</p>
    <h2>Report Data</h2>
    <pre>{safe_report_json}</pre>
    <p class="footer">Review these findings alongside other available evidence.</p>
</body>
</html>
"""

    report_file = Path(output_path)
    report_file.write_text(html_content, encoding="utf-8")

    return str(report_file.resolve())
